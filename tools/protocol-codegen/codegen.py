#!/usr/bin/env python3
"""
Azokle Browser: Universal Protocol Code Generator
Reads JSON schemas from protocols/schemas/ and generates:
1. Rust data models (protocols/generated/rust/)
2. Kotlin data classes (protocols/generated/kotlin/)
3. C++ headers (protocols/generated/cpp/)
"""

import os
import sys
import json

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SCHEMAS_DIR = os.path.join(ROOT_DIR, "protocols", "schemas")
GENERATED_DIR = os.path.join(ROOT_DIR, "protocols", "generated")

RUST_OUT = os.path.join(GENERATED_DIR, "rust")
KOTLIN_OUT = os.path.join(GENERATED_DIR, "kotlin")
CPP_OUT = os.path.join(GENERATED_DIR, "cpp")

def ensure_dirs():
    os.makedirs(RUST_OUT, exist_ok=True)
    os.makedirs(KOTLIN_OUT, exist_ok=True)
    os.makedirs(CPP_OUT, exist_ok=True)

def generate_models():
    ensure_dirs()
    print("[+] Generating language models from schemas...")

